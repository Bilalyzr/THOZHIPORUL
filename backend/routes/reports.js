// GET /api/reports/export?type=...&format=json|csv|xlsx|pdf
// ------------------------------------------------------------
const REPORT_TYPES = ['industry_data', 'park_intelligence', 'missing_submissions', 'compliance',
                      'resource_demand', 'anomaly', 'growth', 'forecast', 'capacity'];

router.get('/export', requireRole(['admin', 'govt']), async (req, res) => {
    try {
        const type = req.query.type || 'industry_data';
        if (!REPORT_TYPES.includes(type)) {
            return res.status(400).json({ error: `Unknown report type. Valid: ${REPORT_TYPES.join(', ')}` });
        }
        const report = await buildReport(type, req);

        await recordAudit(req.user.id, 'REPORT_GENERATED', req.ip, {
            entityType: 'report', entityId: type,
            payload: { format: req.query.format || 'json', rows: report.rows.length }
        });

        if (req.query.format === 'json' || !req.query.format) {
            return res.json({ ...report, count: report.rows.length, caveats: report.caveat ? [report.caveat] : [] });
        }

        if (req.query.format === 'csv') {
            const esc = (v) => v === null || v === undefined ? '' : `"${String(v).replace(/"/g, '""')}"`;
            const lines = [
                ...report.meta.map(([k, v]) => `${esc(k)},${esc(v)}`),
                '',
                report.headers.map(esc).join(','),
                ...report.rows.map(r => r.map(esc).join(','))
            ];
            if (report.caveat) lines.push('', esc('Caveat'), esc(report.caveat));
            res.setHeader('Content-Type', 'text/csv; charset=utf-8');
            res.setHeader('Content-Disposition', `attachment; filename=THOZHIRPORUL_${type}_${Date.now()}.csv`);
            return res.send(Buffer.from('\uFEFF' + lines.join('\n'), 'utf8'));
        }

        if (req.query.format === 'xlsx') {
            // REAL XLSX — typed cells, metadata block, caveat rows.
            const buf = buildXlsx({
                sheetName: type.slice(0, 28),
                title: `THOZHIRPORUL — ${report.title}`,
                meta: [...report.meta, ...(report.caveat ? [['Caveat', report.caveat]] : [])],
                headers: report.headers,
                rows: report.rows
            });
            res.setHeader('Content-Type', 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet');
            res.setHeader('Content-Disposition', `attachment; filename=THOZHIRPORUL_${type}_${Date.now()}.xlsx`);
            return res.send(buf);
        }

        if (req.query.format === 'pdf') {
            const lines = [];
            report.rows.slice(0, 60).forEach(r => lines.push(r.map(v => v === null || v === undefined ? '—' : String(v)).join(' | ')));
            if (report.rows.length > 60) lines.push(`… and ${report.rows.length - 60} more rows (export CSV/XLSX for the full set)`);
            if (report.caveat) lines.push('', `Caveat: ${report.caveat}`);
            res.setHeader('Content-Type', 'application/pdf');
            res.setHeader('Content-Disposition', `attachment; filename=THOZHIRPORUL_${type}_${Date.now()}.pdf`);
            return res.send(Buffer.from(minimalPdf(`THOZHIRPORUL — ${report.title}`, lines), 'utf-8'));
        }

        return res.status(400).json({ error: 'format must be json | csv | xlsx | pdf' });
    } catch (err) {
        console.error('Report Export Error:', err.message);
        res.status(500).send('Server Error');
    }
});

