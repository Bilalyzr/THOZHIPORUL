router.get('/comparison', requireRole(['admin', 'govt']), async (req, res) => {
    try {
        const metric = ['investment', 'employment', 'compliance'].includes(req.query.metric)
            ? req.query.metric : 'investment';
        const a = req.query.periodA, b = req.query.periodB;
        if (!a || !b) return res.status(400).json({ error: 'periodA and periodB required (e.g. 2024, 2025-Q1)' });

        async function totalFor(period) {
            const { year, quarter } = parsePeriod(period);
            if (!year) return 0;
            if (metric === 'investment') {
                const sql = quarter
                    ? `SELECT COALESCE(SUM(f.investment_amount),0) AS v FROM data_submissions ds JOIN financial_data f ON f.submission_id=ds.id WHERE ds.period_year=$1 AND ds.period_quarter=$2`
                    : `SELECT COALESCE(SUM(f.investment_amount),0) AS v FROM data_submissions ds JOIN financial_data f ON f.submission_id=ds.id WHERE ds.period_year=$1`;
                const r = await db.query(sql, quarter ? [year, quarter] : [year]);
                return parseFloat(r.rows[0].v) || 0;
            }
            if (metric === 'employment') {
                const sql = quarter
                    ? `SELECT COALESCE(SUM(COALESCE(e.permanent_employees,0)+COALESCE(e.contract_employees,0)),0) AS v FROM data_submissions ds JOIN employment_data e ON e.submission_id=ds.id WHERE ds.period_year=$1 AND ds.period_quarter=$2`
                    : `SELECT COALESCE(SUM(COALESCE(e.permanent_employees,0)+COALESCE(e.contract_employees,0)),0) AS v FROM data_submissions ds JOIN employment_data e ON e.submission_id=ds.id WHERE ds.period_year=$1`;
                const r = await db.query(sql, quarter ? [year, quarter] : [year]);
                return parseInt(r.rows[0].v) || 0;
            }
            const r = await db.query(
                `SELECT COALESCE(AVG(overall_score),0) AS v FROM compliance_scores WHERE EXTRACT(YEAR FROM score_date)=$1`, [year]);
            return parseFloat(r.rows[0].v) || 0;
        }

        const valA = await totalFor(a);
        const valB = await totalFor(b);
        const deltaPct = valA === 0 ? null : Math.round(((valB - valA) / valA) * 1000) / 10;
        res.json({ metric, periodA: a, periodB: b, valueA: valA, valueB: valB, delta_pct: deltaPct });
    } catch (err) {
        console.error('Comparison Error:', err.message);
        res.status(500).send('Server Error');
    }
});

