// Canonical-unit formatting note used across reports.
const UNIT_NOTE = 'Canonical units: INR / count / KL / kWh / MT. Display scaling (e.g. ₹ Crore) is applied in this table only.';

// Minimal valid PDF (kept for text reports; single page).
function minimalPdf(title, lines) {
    const esc = (s) => String(s).replace(/([()\\])/g, '\\$1');
    const body = [title, '', ...lines].map(l => `(${esc(l)}) Tj 0 -14 Td`).join('\n');
    const content = `BT /F1 9 Tf 40 800 Td\n${body}\nET`;
    const objects = [
        '1 0 obj << /Type /Catalog /Pages 2 0 R >> endobj',
        '2 0 obj << /Type /Pages /Kids [3 0 R] /Count 1 >> endobj',
        '3 0 obj << /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >> endobj',
        `4 0 obj << /Length ${content.length} >> stream\n${content}\nendstream endobj`,
        '5 0 obj << /Type /Font /Subtype /Type1 /BaseFont /Helvetica >> endobj'
    ];
    return `%PDF-1.4\n${objects.join('\n')}\ntrailer << /Root 1 0 R /Size 6 >>\n%%EOF`;
}

// ------------------------------------------------------------
// Dataset builders per report type → { title, meta, headers, rows, caveat }
// ------------------------------------------------------------
async function buildReport(type, req) {
    const generatedBy = req.user ? `${req.user.role} #${req.user.id}` : 'system';
    const year = parseInt(req.query.year) || new Date().getUTCFullYear();
    const metaBase = [
        ['Generated (UTC)', new Date().toISOString()],
        ['Generated by', generatedBy],
        ['Data source', 'THOZHIRPORUL live PostgreSQL (filings, calendar, findings)'],
        ['Report period', `${year}` + (req.query.quarter ? ` Q${req.query.quarter}` : '')],
        ['Filters', req.query.parkId ? `park=${req.query.parkId}` : 'none']
    ];

    if (type === 'industry_data') {
        const { rows } = await db.query(`
            WITH latest AS (
                SELECT DISTINCT ON (ds.industry_id) ds.id, ds.industry_id, ds.period_year, ds.period_quarter
                  FROM data_submissions ds
              ORDER BY ds.industry_id, ds.period_year DESC, ds.period_quarter DESC NULLS LAST)
            SELECT ip.company_name, ip.location, ip.operational_status,
                   p.name AS park, l.period_year, l.period_quarter,
                   f.investment_amount, f.annual_turnover,
                   COALESCE(e.permanent_employees,0)+COALESCE(e.contract_employees,0) AS employment,
                   r.water_consumption, r.power_usage, c.amount_spent AS csr_inr,
                   (SELECT COUNT(*)::int FROM submission_versions sv WHERE sv.submission_id = l.id) AS versions
              FROM industry_profiles ip
         LEFT JOIN industrial_parks p ON p.id = ip.park_id
         LEFT JOIN latest l ON l.industry_id = ip.id
         LEFT JOIN financial_data f ON f.submission_id = l.id
         LEFT JOIN employment_data e ON e.submission_id = l.id
         LEFT JOIN resource_usage r ON r.submission_id = l.id
         LEFT JOIN csr_activities c ON c.submission_id = l.id
          ORDER BY ip.company_name`);
        return {
            title: 'Industry Data Report',
            meta: [...metaBase, ['Units', UNIT_NOTE]],
            headers: ['Company', 'Park', 'Location', 'Operational status', 'Latest period', 'Investment (Cr)', 'Turnover (Cr)', 'Employment', 'Water (KL)', 'Power (kWh)', 'CSR (INR)', 'Versions'],
            rows: rows.map(r => [r.company_name, r.park || '—', r.location || '—', r.operational_status || '—',
                r.period_year ? `${r.period_year}-Q${r.period_quarter ?? 'FY'}` : 'no filing',
                r.investment_amount === null ? null : Math.round(Number(r.investment_amount) / 1e7 * 100) / 100,
                r.annual_turnover === null ? null : Math.round(Number(r.annual_turnover) / 1e7 * 100) / 100,
                r.employment, r.water_consumption, r.power_usage, r.csr_inr, r.versions || 0])
        };
    }

    if (type === 'park_intelligence') {
        const { rows } = await db.query(`
            WITH latest AS (
                SELECT DISTINCT ON (ds.industry_id) ds.id, ds.industry_id
                  FROM data_submissions ds ORDER BY ds.industry_id, submitted_at DESC)
            SELECT p.name, COUNT(ip.id) AS industries,
                   COUNT(ip.id) FILTER (WHERE ip.operational_status = 'OPERATING') AS operating,
                   COALESCE(SUM(f.investment_amount),0) AS invest, COALESCE(SUM(f.annual_turnover),0) AS turnover,
                   COALESCE(SUM(e.permanent_employees + e.contract_employees),0) AS employment,
                   COALESCE(SUM(r.water_consumption),0) AS water, COALESCE(SUM(r.power_usage),0) AS power,
                   p.water_capacity_kl, p.power_capacity_mw
              FROM industrial_parks p
         LEFT JOIN industry_profiles ip ON ip.park_id = p.id
         LEFT JOIN latest l ON l.industry_id = ip.id
         LEFT JOIN financial_data f ON f.submission_id = l.id
         LEFT JOIN employment_data e ON e.submission_id = l.id
         LEFT JOIN resource_usage r ON r.submission_id = l.id
          GROUP BY p.name, p.water_capacity_kl, p.power_capacity_mw ORDER BY invest DESC`);
        return {
            title: 'Park Intelligence Report',
            meta: [...metaBase, ['Units', UNIT_NOTE], ['Basis', 'latest filing per industry']],
            headers: ['Park', 'Industries', 'Operating', 'Investment (Cr)', 'Turnover (Cr)', 'Employment', 'Water latest qtr (KL)', 'Power latest qtr (kWh)', 'Water capacity (KL/day)', 'Power capacity (MW)'],
            rows: rows.map(r => [r.name, r.industries, r.operating,
                Math.round(Number(r.invest) / 1e7 * 100) / 100, Math.round(Number(r.turnover) / 1e7 * 100) / 100,
                r.employment, r.water, r.power, r.water_capacity_kl, r.power_capacity_mw])
        };
    }

    if (type === 'missing_submissions') {
        const matrix = await getFilingMatrix({ year, quarter: req.query.quarter ? parseInt(req.query.quarter) : null });
        return {
            title: 'Missing Submission Report',
            meta: [...metaBase, ['Calendar', 'reporting_periods (admin-configurable deadlines)'],
                   ['Expected filers', `${matrix.summary.expected_industries} (OPERATING/IDLE/TEMPORARILY_CLOSED)`],
                   ['Caveat', 'CLOSED / UNDER_CONSTRUCTION units are not expected to file']],
            headers: ['Company', 'Park', 'Operational status', 'Outstanding periods', 'Overdue now', 'Reminders sent', 'Govt notified'],
            rows: matrix.industries.filter(i => i.outstanding.length > 0).map(i => [
                i.company_name, i.park_name, i.operational_status,
                i.outstanding.map(q => `${year}-Q${q}`).join(', ') || '—',
                i.any_overdue ? 'YES' : 'no',
                Math.max(0, ...i.periods.map(p => p.reminder_no)) || 0,
                i.periods.some(p => p.gov_notified) ? 'YES' : 'no'])
        };
    }

    if (type === 'compliance') {
        const scores = await db.query(`
            WITH latest AS (SELECT DISTINCT ON (industry_id) industry_id, overall_score
                              FROM compliance_scores ORDER BY industry_id, score_date DESC)
            SELECT ip.company_name, ls.overall_score, ip.compliance_score AS profile_sync,
                   (SELECT COUNT(*)::int FROM compliance_violations v WHERE v.industry_id = ip.id AND v.status <> 'resolved') AS open_violations,
                   (SELECT COUNT(*)::int FROM data_findings f WHERE f.industry_id = ip.id AND f.status = 'open') AS open_findings
              FROM industry_profiles ip LEFT JOIN latest ls ON ls.industry_id = ip.id ORDER BY ip.company_name`);
        return {
            title: 'Compliance Report',
            meta: [...metaBase, ['Scoring', 'computed daily from violations, findings and filing timeliness']],
            headers: ['Company', 'Latest score', 'Synced profile score', 'Open violations', 'Open data findings'],
            rows: scores.rows.map(r => [r.company_name, r.overall_score, r.profile_sync, r.open_violations, r.open_findings])
        };
    }

    if (type === 'resource_demand') {
        const [water, power] = await Promise.all([
            quarterlySeries('water', 'state', null), quarterlySeries('power', 'state', null)
        ]);
        const rows = [];
        const len = Math.max(water.length, power.length);
        for (let i = 0; i < len; i++) {
            const w = water[Math.max(0, water.length - len + i)] || {};
            const p = power[Math.max(0, power.length - len + i)] || {};
            const wp = water.length > 1 && i >= water.length - len + 1 && water[i - 1] && water[i - 1].value > 0
                ? Math.round(((water[i].value - water[i - 1].value) / water[i - 1].value) * 1000) / 10 : null;
            rows.push([`${w.year || p.year}-${w.quarter || p.quarter}`,
                w.value ?? null, wp, p.value ?? null, null]);
        }
        return {
            title: 'Resource Demand Report',
            meta: [...metaBase, ['Source', 'industry filings aggregated per quarter (statewide)'], ['Units', 'KL and kWh per quarter']],
            headers: ['Quarter', 'Water demand (KL)', 'Water QoQ %', 'Power demand (kWh)', 'Power QoQ %'],
            rows,
            caveat: water.length < 2 || power.length < 2 ? 'Fewer than two quarters of history — growth columns are intentionally blank.' : null
        };
    }

    if (type === 'anomaly') {
        const { rows } = await db.query(`
            SELECT f.finding_type, f.rule_id, ip.company_name, f.period_year, f.period_quarter,
                   f.metric, f.observed_value, f.expected_value, f.change_pct, f.severity, f.reason, f.status, f.detected_at
              FROM data_findings f JOIN industry_profiles ip ON ip.id = f.industry_id
          ORDER BY CASE f.severity WHEN 'critical' THEN 0 WHEN 'high' THEN 1 WHEN 'warning' THEN 2 ELSE 3 END, f.detected_at DESC
             LIMIT 500`);
        return {
            title: 'Anomaly & Consistency Findings Report',
            meta: [...metaBase, ['Detectors', 'period-over-change %, IQR fence, quota/consistency rules'],
                   ['Caveat', 'metrics with insufficient history are skipped (never scored) — see data_findings.evidence']],
            headers: ['Detected', 'Type', 'Rule', 'Company', 'Period', 'Metric', 'Observed', 'Expected', 'Change %', 'Severity', 'Status', 'Reason'],
            rows: rows.map(r => [new Date(r.detected_at).toISOString(), r.finding_type, r.rule_id, r.company_name,
                `${r.period_year}-Q${r.period_quarter ?? 'FY'}`, r.metric, r.observed_value, r.expected_value,
                r.change_pct, r.severity, r.status, r.reason])
        };
    }

    if (type === 'growth') {
        const metric = METRIC_CONFIG[req.query.metric] ? req.query.metric : 'employment';
        const series = await quarterlySeries(metric, 'state', null);
        return {
            title: `Growth Report — ${metric} (statewide)`,
            meta: [...metaBase, ['Unit', METRIC_CONFIG[metric].unit], ['Method', 'QoQ = vs previous filed quarter; YoY = vs same quarter prior year']],
            headers: ['Quarter', 'Value', 'QoQ %', 'YoY %'],
            rows: series.map((p, i) => {
                const prev = series[i - 1];
                const prevY = series.find(x => x.year === p.year - 1 && x.quarter === p.quarter);
                return [`${p.year}-Q${p.quarter}`, p.value,
                    prev && prev.value > 0 ? Math.round(((p.value - prev.value) / prev.value) * 1000) / 10 : null,
                    prevY && prevY.value > 0 ? Math.round(((p.value - prevY.value) / prevY.value) * 1000) / 10 : null];
            }),
            caveat: series.length < 2 ? 'Insufficient history for growth columns.' : null
        };
    }

    if (type === 'forecast') {
        const metric = METRIC_CONFIG[req.query.metric] ? req.query.metric : 'power';
        const fc = await forecast(metric, 'state', null, 4, { persist: false, generatedBy: `report:${req.user.id}` });
        return {
            title: `Forecast Report — ${metric} (statewide, next 4 quarters)`,
            meta: [...metaBase, ['Model', fc.model || 'none'], ['Training quarters', fc.training_periods], ['Unit', fc.unit]],
            headers: ['Period', 'Predicted', 'Lower bound', 'Upper bound'],
            rows: fc.projection.map((p, i) => [p.period, p.value, fc.band[i].low, fc.band[i].high]),
            caveat: fc.data_status !== 'OK'
                ? `INSUFFICIENT_DATA: ${fc.available_points} quarter(s) available; ${fc.minimum_required}. No projection produced.`
                : (fc.caveat || null)
        };
    }

    if (type === 'capacity') {
        const parks = (await db.query('SELECT * FROM industrial_parks ORDER BY id')).rows;
        const rows = [];
        for (const p of parks) {
            for (const metric of ['water', 'power']) {
                const series = await quarterlySeries(metric, 'park', p.id);
                const current = series.length ? series[series.length - 1].value : null;
                const fc = await forecast(metric, 'park', p.id, 4, { persist: false });
                const projected = fc.data_status === 'OK'
                    ? Math.round(fc.projection.reduce((s, x) => s + x.value, 0) / fc.projection.length)
                    : current;
                const capacity = metric === 'water'
                    ? (Number(p.water_capacity_kl) > 0 ? Math.round(Number(p.water_capacity_kl) * 91) : null)
                    : (Number(p.power_capacity_mw) > 0 ? Math.round(Number(p.power_capacity_mw) * 1000 * 2190) : null);
                const gap = capacity !== null && projected !== null ? projected - capacity : null;
                const risk = capacity === null ? 'NOT_CONFIGURED' : projected === null ? 'NO_DEMAND_DATA'
                    : (projected / capacity > 1 ? 'HIGH' : projected / capacity > 0.85 ? 'MEDIUM' : 'LOW');
                rows.push([p.name, metric, current, projected,
                    capacity, gap, risk,
                    fc.data_status === 'OK' ? fc.model : `insufficient data (${fc.available_points} qtrs)`]);
            }
        }
        return {
            title: 'Infrastructure Capacity / Demand Report',
            meta: [...metaBase,
                   ['Capacity basis', 'water: configured KL/day × 91; power: configured MW × 1000 × 2190h'],
                   ['Caveat', 'NOT_CONFIGURED = no capacity value set for the park — configure industrial_parks before planning.']],
            headers: ['Park', 'Resource', 'Current demand (qtr)', 'Projected (4-qtr mean)', 'Capacity (qtr)', 'Gap', 'Risk', 'Forecast model'],
            rows
        };
    }

    throw new Error('UNKNOWN_REPORT_TYPE');
}

