// chart-data / comparison / log / executive-summary (preserved).
// ------------------------------------------------------------
function parsePeriod(p) {
    if (!p) return {};
    const m = String(p).match(/^(\d{4})(?:[-/](Q([1-4])|S([12]))?)?$/i);
    if (!m) return {};
    const quarter = m[3] ? parseInt(m[3]) : (m[4] ? parseInt(m[4]) : null);
    return { year: parseInt(m[1]), quarter };
}

